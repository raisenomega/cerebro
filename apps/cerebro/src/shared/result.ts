/**
 * Result<T, E> — manejo de errores tipado, sin `throw` de control (regla
 * grado bancario §2.1 del brief). Todo borde de la aplicación devuelve un
 * Result; el `throw` queda solo para invariantes de arranque (config faltante).
 */

export interface Ok<T> {
  readonly ok: true;
  readonly value: T;
}

export interface Err<E> {
  readonly ok: false;
  readonly error: E;
}

export type Result<T, E> = Ok<T> | Err<E>;

export const ok = <T>(value: T): Ok<T> => ({ ok: true, value });
export const err = <E>(error: E): Err<E> => ({ ok: false, error });

export const isOk = <T, E>(r: Result<T, E>): r is Ok<T> => r.ok;
export const isErr = <T, E>(r: Result<T, E>): r is Err<E> => !r.ok;
